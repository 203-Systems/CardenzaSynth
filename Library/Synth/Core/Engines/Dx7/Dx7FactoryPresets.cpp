const Dx7FactoryPresetDefinition* FindDx7FactoryPreset(std::string_view presetId)
{
  const auto iterator = std::find_if(kDx7FactoryPresets.begin(), kDx7FactoryPresets.end(), [&](const Dx7FactoryPresetDefinition& preset) {
  return preset.id == presetId;
  });
  return iterator == kDx7FactoryPresets.end() ? nullptr : &(*iterator);
}

