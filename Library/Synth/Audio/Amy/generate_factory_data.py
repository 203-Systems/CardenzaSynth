"""Regenerate compact UI/DSP source data from the pinned AMY factory bank."""
import ast
from pathlib import Path

root = Path(__file__).resolve().parents[4]
vendor = root / "Library/third_party/amy/amy"
dx7 = (vendor / "default-dx7-patches.bin").read_bytes()
juno = next(ast.literal_eval(n.value) for n in ast.parse((vendor / "juno.py").read_text()).body
            if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "_PATCHES" for t in n.targets))
assert len(dx7) >= 128 * 156 and len(juno) == 128
lines = ["// Generated by generate_factory_data.py from pinned AMY fm.py/juno.py input data.",
         "#pragma once", "#include <cstdint>", "namespace synth::factory {",
         "inline constexpr std::uint8_t kDx7[128][156] = {"]
for i in range(128):
    lines.append("  {" + ",".join(map(str, dx7[i * 156:(i + 1) * 156])) + "},")
lines += ["};", "inline constexpr std::uint8_t kJuno[128][18] = {"]
for name, data in juno:
    lines.append("  {" + ",".join(map(str, data)) + "},")
lines += ["};", "}  // namespace synth::factory", ""]
Path(__file__).with_name("FactoryData.h").write_text("\n".join(lines))
