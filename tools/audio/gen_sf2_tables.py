#!/usr/bin/env python3
"""Writes Library/Synth/Audio/SoundFont/Sf2Tables.inc: the conversion tables of the SoundFont voice.

The voice works in integers; everything a note needs from pow, log or tan comes from these tables, so the
host tests and the board compute the same bits. Run it again only when a table changes:

    python3 tools/audio/gen_sf2_tables.py > Library/Synth/Audio/SoundFont/Sf2Tables.inc
"""

import math

SAMPLE_RATE = 44100
CONTROL_FRAMES = 64
KEY_ZERO_HZ = 8.1757989156  # MIDI key 0, the SoundFont's zero of absolute cents


def emit(name, kind, values, per_line=8):
    print("inline constexpr %s %s[%d] = {" % (kind, name, len(values)))
    for start in range(0, len(values), per_line):
        print("    " + ", ".join("%du" % value for value in values[start:start + per_line]) + ",")
    print("};")
    print()


print("// Generated by tools/audio/gen_sf2_tables.py. Do not edit.")
print()

# 2^(i / 1200) in Q30, one octave of cents and its end point for interpolation.
emit("kExp2Q30", "std::uint32_t", [round((1 << 30) * 2.0 ** (i / 1200.0)) for i in range(1201)])

# Gain of an attenuation in centibels, Q15: 10^(-cB / 200). Past 1440 cB the table is silent.
emit("kGainQ15", "std::uint16_t", [round(32768 * 10.0 ** (-i / 200.0)) for i in range(1442)], 12)

# The default velocity curve as an attenuation, in 1/16 cB: 400 log10(127 / velocity), 96 dB at most.
emit("kVelocityCbQ4", "std::uint16_t",
     [960 * 16] + [min(960 * 16, round(16 * 400 * math.log10(127.0 / v))) for v in range(1, 128)], 12)

# The lowpass's g = tan(pi f / rate) in Q24 for a cutoff of 1500 + 25 i cents, held under 0.45 of the rate.
cutoffs = []
for i in range(482):
    hz = min(KEY_ZERO_HZ * 2.0 ** ((1500 + 25 * i) / 1200.0), 0.45 * SAMPLE_RATE)
    cutoffs.append(round((1 << 24) * math.tan(math.pi * hz / SAMPLE_RATE)))
emit("kFilterGQ24", "std::uint32_t", cutoffs)

# The lowpass's k = 1 / Q in Q24 for a resonance of 10 i cB; 0 cB is Q = 0.707, no peak.
emit("kResonanceKQ24", "std::uint32_t",
     [round((1 << 24) / 10.0 ** ((i - 3.01) / 20.0)) for i in range(26)])

print("// An LFO's phase step per control step (a turn is 2^32) at 0 cents, 8.176 Hz.")
print("inline constexpr std::uint32_t kLfoStepAtZeroCents = %du;" % round(KEY_ZERO_HZ * CONTROL_FRAMES / SAMPLE_RATE * 2.0 ** 32))
print("// Control steps in a second, Q8.")
print("inline constexpr std::uint32_t kControlStepsPerSecondQ8 = %du;" % round(256.0 * SAMPLE_RATE / CONTROL_FRAMES))
