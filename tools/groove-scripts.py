#!/usr/bin/env python3
"""Generates tests/groove/tour.script (one screenshot per state) and tests/groove/motion.script
(frame-by-frame captures for the motion GIFs). Keys: ADD = 0,13 (del), SUB = 1,13, ENTER, space = PLAY."""
import pathlib

ADD, SUB = "0,13", "1,13"


class Script:
    def __init__(self, header):
        self.lines = [header]
        self.count = 0

    def act(self, *commands):
        self.lines.extend(commands)

    def wait(self, frames):
        self.lines.append(f"wait {frames}")

    def shot(self, name):
        self.lines.append(f"screenshot {name}")

    def frames(self, section, ticks):
        for _ in range(ticks):
            self.lines.append(f"screenshot {section}/{self.count:04d}")
            self.count += 1

    def scene(self, number):
        # Hold ESC: the GRID columns are the scenes.
        self.act("down esc", f"tap 0,{8 + number}", "up esc")

    def page(self, index):
        # Hold CTRL: the GRID keys are the pages of the current scene.
        self.act("down ctrl", f"tap {index // 4},{9 + index % 4}", "up ctrl")

    def write(self, path):
        pathlib.Path(path).write_text("\n".join(self.lines) + "\n")


def drum_loop(s, between=None):
    # Hold a pad, tap steps: kick on the beats, snare on 5 and 13, hats on the offbeats.
    s.act("down 3,1"); [s.act(f"tap {r},9") for r in range(4)]; s.act("up 3,1")
    if between: between()
    s.act("down 2,2", "tap 1,9", "tap 3,9", "up 2,2")
    if between: between()
    s.act("down 2,3", "tap 0,11", "tap 1,11", "tap 2,11", "tap 3,11", "up 2,3")


